"""Unit tests for scripts/generate-nginx-disabled-apps.py.

Every path is a temporary file: the script's .env, template and output
constants are pointed at tmp_path, so nothing under configs/ is read or
written. One test reads the real template, to prove the script parses it.
"""

import re

import pytest

pytestmark = pytest.mark.unit

TEMPLATE = """\
map $request_uri $app_name {
    default                Homepage;
    ~^/sonarr(?:[/?]|$)    Sonarr;
}

map $request_uri $app_profile {
    default                HOMEPAGE_PROFILE;
    ~^/stub_status(?:\\?|$) "";
    ~^/nzbhydra2(?:[/?]|$) NZBHYDRA2_PROFILE;
    ~^/sonarr(?:[/?]|$)    SONARR_PROFILE;
    ~^/whisparr(?:[/?]|$)  WHISPARR_PROFILE;
}
"""


@pytest.fixture
def generator(load_script, tmp_path, monkeypatch):
    module = load_script("generate-nginx-disabled-apps.py")
    monkeypatch.setattr(module, "ENV_FILE", tmp_path / ".env")
    monkeypatch.setattr(module, "TEMPLATE_FILE", tmp_path / "default.conf.template")
    monkeypatch.setattr(
        module, "OUTPUT_FILE", tmp_path / "generated" / "disabled-apps.conf"
    )
    (tmp_path / "default.conf.template").write_text(TEMPLATE)
    return module


def _entries(output: str) -> dict[str, str]:
    """The written map entries, key to value, comments left out."""
    return dict(
        line.rstrip(";").split()
        for line in output.splitlines()
        if line and not line.startswith("#")
    )


def test_read_profiles_without_an_env_file(generator, tmp_path):
    assert generator.read_profiles(tmp_path / "missing") == {}


def test_read_profiles_reads_only_profile_flags(generator, tmp_path):
    env = tmp_path / ".env"
    env.write_text(
        "# NZBHYDRA2_PROFILE=disabled\n"
        "NZBHYDRA2_PROFILE=disabled\n"  # pragma: allowlist secret
        "SONARR_PROFILE=enabled\n"
        "SONARR_HTTP_PORT=8989\n"
        "WHISPARR_PROFILE=enabled # trailing note\n"
    )
    assert generator.read_profiles(env) == {
        "NZBHYDRA2_PROFILE": False,
        "SONARR_PROFILE": True,
    }


def test_read_app_profiles_parses_the_map(generator):
    default, entries = generator.read_app_profiles(TEMPLATE)
    assert default == "HOMEPAGE_PROFILE"
    assert entries == [
        ("~^/stub_status(?:\\?|$)", ""),
        ("~^/nzbhydra2(?:[/?]|$)", "NZBHYDRA2_PROFILE"),
        ("~^/sonarr(?:[/?]|$)", "SONARR_PROFILE"),
        ("~^/whisparr(?:[/?]|$)", "WHISPARR_PROFILE"),
    ]


def test_read_app_profiles_refuses_a_template_without_the_map(generator):
    with pytest.raises(SystemExit, match=r"no \$app_profile map"):
        generator.read_app_profiles("map $request_uri $app_name {\n}\n")


def test_main_marks_disabled_profiles(generator, tmp_path):
    (tmp_path / ".env").write_text(
        "HOMEPAGE_PROFILE=enabled\nNZBHYDRA2_PROFILE=disabled\nSONARR_PROFILE=enabled\n"  # pragma: allowlist secret
    )
    generator.main()

    output = generator.OUTPUT_FILE.read_text()
    assert output.startswith("# Generated by scripts/generate-nginx-disabled-apps.py")
    assert _entries(output) == {
        "default": "0",
        "~^/stub_status(?:\\?|$)": "0",
        "~^/nzbhydra2(?:[/?]|$)": "1",
        "~^/sonarr(?:[/?]|$)": "0",
        # Missing from .env: counts as enabled.
        "~^/whisparr(?:[/?]|$)": "0",
    }


def test_main_disables_the_default_with_homepage(generator, tmp_path):
    """Every path no key matches is Homepage's, so it follows Homepage's flag."""
    (tmp_path / ".env").write_text("HOMEPAGE_PROFILE=disabled\n")
    generator.main()

    entries = _entries(generator.OUTPUT_FILE.read_text())
    assert entries["default"] == "1"
    # nginx's own status page has no profile, and is never refused.
    assert entries["~^/stub_status(?:\\?|$)"] == "0"


def test_main_without_an_env_file_enables_everything(generator):
    generator.main()

    assert set(_entries(generator.OUTPUT_FILE.read_text()).values()) == {"0"}


def test_the_real_template_parses(load_script):
    """Every key is a path regex, every value a profile or nothing."""
    module = load_script("generate-nginx-disabled-apps.py")
    default, entries = module.read_app_profiles(module.TEMPLATE_FILE.read_text())

    assert default == "HOMEPAGE_PROFILE"
    assert entries
    for key, profile in entries:
        assert key.startswith("~^/"), key
        assert profile == "" or re.fullmatch(r"[A-Z0-9_]+_PROFILE", profile), profile
