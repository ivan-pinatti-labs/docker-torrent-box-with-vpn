"""Write configs/nginx/generated/disabled-apps.conf from .env's *_PROFILE flags.

nginx answers the path of an app whose profile is off with a page saying so,
instead of the bare 502 it gives when the app's name does not resolve (#415).
Which path belongs to which profile is the `$app_profile` map in
configs/nginx/templates/default.conf.template; this reads that map, and writes
the entries of its `$app_disabled` map, 1 for a path whose profile is not
`enabled` and 0 otherwise. A path whose map entry names no profile
(/stub_status) is never disabled, and the map's default, Homepage's, decides
every path no key matches.

Run on every `make start`, which reloads a running nginx afterwards, so
flipping a profile and running it again is enough. A profile missing from .env
counts as enabled, the way scripts/generate-homepage-services.py keeps an app
whose flag it cannot find: a parsing mismatch should not hide an app. So does
every profile when there is no .env yet, since nginx needs the file either way.
"""

import re
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
ENV_FILE = REPO_ROOT / ".env"
TEMPLATE_FILE = REPO_ROOT / "configs/nginx/templates/default.conf.template"
OUTPUT_FILE = REPO_ROOT / "configs/nginx/generated/disabled-apps.conf"


def read_profiles(env_file: Path) -> dict[str, bool]:
    """Each *_PROFILE in .env, True when it is `enabled`."""
    if not env_file.is_file():
        return {}
    profiles = {}
    for line in env_file.read_text().splitlines():
        m = re.match(r"^([A-Z0-9_]+_PROFILE)=(\S*)$", line)
        if m:
            profiles[m.group(1)] = m.group(2) == "enabled"
    return profiles


def read_app_profiles(template: str) -> tuple[str, list[tuple[str, str]]]:
    """The `$app_profile` map: its default profile, and each key with its own.

    A value of "" (a path with no app of its own) comes back as "".
    """
    block = re.search(
        r"^map \$request_uri \$app_profile \{\n(.*?)^\}", template, re.M | re.S
    )
    if block is None:
        raise SystemExit(f"ERROR: no $app_profile map in {TEMPLATE_FILE}.")
    default = ""
    entries = []
    for line in block.group(1).splitlines():
        key, value = line.split()
        value = value.rstrip(";").strip('"')
        if key == "default":
            default = value
        else:
            entries.append((key, value))
    return default, entries


def render(default: str, entries: list[tuple[str, str]], profiles: dict) -> str:
    def disabled(profile: str) -> int:
        return int(bool(profile) and not profiles.get(profile, True))

    width = max(len(key) for key, _ in entries)
    lines = [
        "# Generated by scripts/generate-nginx-disabled-apps.py from .env on every",
        "# `make start`. Edit .env's *_PROFILE values, not this file.",
        f"default {disabled(default)};",
    ]
    lines += [f"{key:<{width}} {disabled(profile)};" for key, profile in entries]
    return "\n".join(lines) + "\n"


def main() -> None:
    """Write OUTPUT_FILE. A failure raises SystemExit; reaching the end is success."""
    default, entries = read_app_profiles(TEMPLATE_FILE.read_text())
    OUTPUT_FILE.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_FILE.write_text(render(default, entries, read_profiles(ENV_FILE)))


if __name__ == "__main__":
    main()
